"""Test inventory of the kernel unit tests.

Each application has one expected set for each twister scenario, in
<application>/inventory/<scenario>.txt. Each line of the file is one test:

    run mutex_unit.lock_free_mutex
    skip mutex_unit.lock_from_user_mode

The state is "run" or "skip". "skip" means that each run of the test was a
skip, or that the test did not run (for example, the predicate of its suite
was false). The lines are sorted. A line that starts with "#" is a comment.

common/src/test_inventory.c compares the tests of the binary with the
expected set after all suites ran. If they are not equal, the binary fails.

Commands:

  gen --app-dir <dir> --scenario <name> --build-dir <dir>
      cmake/kernel_unit.cmake runs this command when an application is
      configured. It writes <build dir>/kernel_unit/kernel_unit_inventory.h
      (the expected set as C data) and <build dir>/test_inventory.dest (the
      path of the expected set). If the expected set is not correct, the
      command prints the error and exits with status 1.

  update <twister output or build dir>...
      Copies the actual set of each test run (test_inventory.actual.txt in
      the build directory) to the expected set of its scenario. Then review
      the diff with "git diff". The command also prints each expected set
      that had no run, for example the set of a removed scenario.
"""

import argparse
import json
import re
import sys
from pathlib import Path

STATES = ("run", "skip")
LINE = re.compile(r"^(run|skip) ([A-Za-z_][A-Za-z0-9_]*)\.([A-Za-z_][A-Za-z0-9_]*)$")
INVENTORY_DIR = "inventory"
ACTUAL = "test_inventory.actual.txt"
DEST = "test_inventory.dest"

# The modes of common/src/test_inventory.c.
MODE_OFF = 0
MODE_NO_FILE = 1
MODE_CHECK = 2

HEADER = """\
# Expected test inventory of the twister scenario {scenario}.
# Each line is "<state> <suite>.<test>". The state is "run" or "skip".
# To regenerate, see "Test inventory" in tests/kernel/unit/README.rst.
"""


class InventoryError(Exception):
    pass


def parse(path):
    """Return {(suite, test): state} of an expected or actual set."""
    tests = {}
    for number, line in enumerate(path.read_text().splitlines(), start=1):
        line = line.strip()
        if not line or line.startswith("#"):
            continue
        match = LINE.match(line)
        if not match:
            raise InventoryError(f"{path}:{number}: not '<run|skip> <suite>.<test>': {line}")
        state, suite, test = match.groups()
        if (suite, test) in tests:
            raise InventoryError(f"{path}:{number}: {suite}.{test} occurs two times")
        tests[(suite, test)] = state
    return tests


def render(scenario, tests):
    lines = [f"{state} {suite}.{test}" for (suite, test), state in sorted(tests.items())]
    return HEADER.format(scenario=scenario) + "\n".join(lines) + "\n"


def c_string(text):
    # A JSON string of ASCII text is also a correct C string literal.
    return json.dumps(str(text), ensure_ascii=True)


def scenario_file(app_dir, scenario):
    return Path(app_dir) / INVENTORY_DIR / f"{scenario}.txt"


def cmd_gen(args):
    app_dir = Path(args.app_dir).resolve()
    build_dir = Path(args.build_dir).resolve()
    expected = scenario_file(app_dir, args.scenario)

    tests = {}
    if not (app_dir / INVENTORY_DIR).is_dir():
        mode = MODE_OFF
    elif not expected.is_file():
        mode = MODE_NO_FILE
    else:
        mode = MODE_CHECK
        tests = parse(expected)

    out_dir = build_dir / "kernel_unit"
    out_dir.mkdir(parents=True, exist_ok=True)
    lines = [
        "/* Generated by common/test_inventory.py. Do not edit. */",
        f"#define KERNEL_UNIT_INVENTORY_SCENARIO {c_string(args.scenario)}",
        f"#define KERNEL_UNIT_INVENTORY_EXPECTED {c_string(expected)}",
        f"#define KERNEL_UNIT_INVENTORY_ACTUAL {c_string(build_dir / ACTUAL)}",
        f"#define KERNEL_UNIT_INVENTORY_MODE {mode}",
        "static const struct kernel_unit_inventory_entry kernel_unit_inventory_expected[] = {",
    ]
    for (suite, test), state in sorted(tests.items()):
        lines.append(f'\t{{"{suite}", "{test}", KERNEL_UNIT_INVENTORY_{state.upper()}}},')
    lines += ["\t{NULL, NULL, KERNEL_UNIT_INVENTORY_RUN},", "};", ""]
    header = out_dir / "kernel_unit_inventory.h"
    text = "\n".join(lines)
    # Write only a change, so that a configure step does not rebuild the source.
    if not header.is_file() or header.read_text() != text:
        header.write_text(text)
    (build_dir / DEST).write_text(f"{args.scenario}\n{expected}\n")
    return 0


def cmd_update(args):
    dests = []
    for root in args.dirs:
        root = Path(root)
        if (root / DEST).is_file():
            dests.append(root / DEST)
        dests.extend(sorted(p for p in root.rglob(DEST) if p != root / DEST))
    if not dests:
        print(f"test_inventory: no {DEST} below {' '.join(args.dirs)}", file=sys.stderr)
        return 1

    errors = 0
    seen = {}
    counts = {"new": 0, "changed": 0, "unchanged": 0}
    for dest in dests:
        scenario, expected = dest.read_text().splitlines()[:2]
        expected = Path(expected)
        actual = dest.parent / ACTUAL
        if not actual.is_file():
            print(f"test_inventory: ERROR: {scenario}: no actual set, the binary did not run "
                  f"({dest.parent})", file=sys.stderr)
            errors += 1
            continue
        if expected in seen:
            print(f"test_inventory: ERROR: {scenario}: two runs ({seen[expected]} and "
                  f"{dest.parent})", file=sys.stderr)
            errors += 1
            continue
        seen[expected] = dest.parent
        text = render(scenario, parse(actual))
        if not expected.is_file():
            counts["new"] += 1
            print(f"test_inventory: new {expected}")
        elif expected.read_text() != text:
            counts["changed"] += 1
            print(f"test_inventory: changed {expected}")
        else:
            counts["unchanged"] += 1
            continue
        expected.parent.mkdir(exist_ok=True)
        expected.write_text(text)

    for inventory_dir in sorted({p.parent for p in seen}):
        for path in sorted(inventory_dir.glob("*.txt")):
            if path not in seen:
                print(f"test_inventory: WARNING: no run for {path}. If the scenario is "
                      f"removed, delete the file.")

    print(f"test_inventory: {counts['new']} new, {counts['changed']} changed, "
          f"{counts['unchanged']} unchanged, {errors} errors")
    return 1 if errors else 0


def main():
    parser = argparse.ArgumentParser(description=__doc__,
                                     formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = parser.add_subparsers(dest="command", required=True)
    gen = sub.add_parser("gen", help="write the expected set as C data (cmake)")
    gen.add_argument("--app-dir", required=True)
    gen.add_argument("--scenario", required=True)
    gen.add_argument("--build-dir", required=True)
    gen.set_defaults(func=cmd_gen)
    update = sub.add_parser("update", help="copy the actual sets to the expected sets")
    update.add_argument("dirs", nargs="+", help="twister output directory or build directory")
    update.set_defaults(func=cmd_update)
    args = parser.parse_args()
    try:
        return args.func(args)
    except InventoryError as error:
        print(f"test_inventory: ERROR: {error}", file=sys.stderr)
        return 1


if __name__ == "__main__":
    sys.exit(main())
